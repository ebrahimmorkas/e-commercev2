// Fields gated together with paymentScanner behind
// CompanyMaster.showPaymentQRCodeAndBankDetails (+
// WebsiteMaster.isShowingPaymentQRCodeAndBankDetailsFeatureOn).
const BANK_TRANSFER_FIELDS = [
    'bankAccountHolderName', 'bankName', 'bankAccountNumber', 'ifscCode', 'branchName',
    'swiftCode', 'bankAccountType'
];

// '' and undefined/null are the same "empty" value for this comparison -
// Joi normalizes bankAccountType's '' to null before this runs, but the
// plain string bank fields (bankAccountHolderName etc.) are only
// .allow('', null), so an untouched form field can legitimately arrive as
// either depending on which one the caller used.
const normalizeEmpty = (value) => (value === undefined || value === '' ? null : value);

// Checks whether the request is actually CHANGING the bank-transfer group
// (any bank field whose incoming value differs from what's already stored,
// or a new paymentScanner file) or the partnerCertificate file, and if so,
// verifies the vendor is entitled to it. Returns null when nothing gated
// was actually touched (caller proceeds normally), otherwise returns the
// first failing returnResult().
//
// Deliberately diff-based rather than presence-based: a caller that sends
// its whole settings object on every save (not just the fields it means to
// change) would otherwise trip this gate on every single save, for a group
// it isn't even trying to edit - confirmed live via the admin Company
// Settings page, which 403'd on saving an unrelated toggle for a vendor not
// entitled to Bank Transfer, purely because it sent bankAccountHolderName:
// '' etc. alongside everything else.
const checkPaymentDetailsEntitlements = async (vendorId, data, files, companyMasterData, websiteMasterData, existingSettings = null) => {
    try {
        const bankGroupTouched = BANK_TRANSFER_FIELDS.some((field) => {
            if (data[field] === undefined) return false;
            const currentValue = existingSettings ? existingSettings[field] : undefined;
            return normalizeEmpty(data[field]) !== normalizeEmpty(currentValue);
        }) || !!files?.paymentScanner?.[0];
        if (bankGroupTouched) {
            const check = await common.checkFeatureOnOrOff(
                vendorId, websiteMasterData, companyMasterData,
                'isShowingPaymentQRCodeAndBankDetailsFeatureOn', 'showPaymentQRCodeAndBankDetails'
            );
            if (!check.isSuccess) return check;
        }

        const certificateTouched = !!files?.partnerCertificate?.[0];
        if (certificateTouched) {
            const check = await common.checkFeatureOnOrOff(
                vendorId, websiteMasterData, companyMasterData,
                'isShowingPartnerCertificateFeatureOn', 'isShowingPartnerCertificateFeatureOn'
            );
            if (!check.isSuccess) return check;
        }

        return null;
    } catch (err) {
        throw err;
    }
};

// Keeps the 3 return-Free-Cash fields internally consistent regardless of
// which subset of them a given create/update request actually touched -
// refundWholeFreeCashAmount/amountToRefund are meaningless (and forced back
// to their inapplicable default) whenever returnFreeCashOnOrderReturn is
// off, and amountToRefund specifically is meaningless whenever the whole
// amount is being refunded.
const normalizeFreeCashReturnFields = (target) => {
    if (target.returnFreeCashOnOrderReturn !== true) {
        target.refundWholeFreeCashAmount = false;
        target.amountToRefund = null;
    } else if (target.refundWholeFreeCashAmount === true) {
        target.amountToRefund = null;
    }
};

// Store country/state/city (the tax location when a customer's is unknown -
// see taxCalculationService.js) must be a consistent, active chain the vendor
// serves: country in CompanyMaster.allowedCountries, state inside that
// country, city inside that state. A state/city needs its parent set.
// Checked against the values the document will END UP with, so a partial
// update can't leave a state pointing at a different country.
const validateStoreLocation = async (data, companyMasterData, existingSettings = null) => {
    try {
        const pick = (field) => (data[field] !== undefined ? data[field] : (existingSettings ? existingSettings[field] : null)) || null;
        const countryId = pick('storeCountryId');
        const stateId = pick('storeStateId');
        const cityId = pick('storeCityId');

        if (!countryId && (stateId || cityId)) {
            return common.returnResult(false, 400, 'Select a store country before choosing a store state or city.');
        }
        if (!stateId && cityId) {
            return common.returnResult(false, 400, 'Select a store state before choosing a store city.');
        }
        if (!countryId) {
            return null;
        }

        const allowedCountryIds = (companyMasterData?.allowedCountries || []).map((id) => id.toString());
        if (!allowedCountryIds.includes(countryId.toString())) {
            return common.returnResult(false, 400, 'The selected store country is not one of the countries your store serves.');
        }
        const country = await CountryMaster.findOne({ _id: countryId, status: 'A' }).select('_id').lean();
        if (!country) {
            return common.returnResult(false, 400, 'The selected store country is not available.');
        }
        if (stateId) {
            const state = await StateMaster.findOne({ _id: stateId, country_id: countryId, status: 'A' }).select('_id').lean();
            if (!state) {
                return common.returnResult(false, 400, 'The selected store state does not belong to the selected store country.');
            }
        }
        if (cityId) {
            const city = await CityMaster.findOne({ _id: cityId, state_id: stateId, status: 'A' }).select('_id').lean();
            if (!city) {
                return common.returnResult(false, 400, 'The selected store city does not belong to the selected store state.');
            }
        }
        return null;
    } catch (err) {
        throw err;
    }
};

const ORDER_STEP_FIELD_LABELS = {
    orderCancellationNotAllowedAfterStep: 'Cancellation not allowed after step',
    markPaymentCompletedAtStep: 'Mark payment as done at step',
    deliveryAgentFromStep: 'Delivery agent - from step',
    deliveryAgentToStep: 'Delivery agent - to step'
};

// The order-step settings must name steps of the workflow the platform
// assigned to this vendor (CompanyMaster.orderSteps). Diff-based like
// checkPaymentDetailsEntitlements: the admin page sends every field on every
// save, and a value saved before the vendor was given a different workflow
// must not block saving something unrelated - only a CHANGED value is checked.
// The delivery-agent pair is re-checked as a pair whenever either half changes.
const validateOrderStepSettings = async (data, companyMasterData, websiteMasterData, existingSettings = null) => {
    try {
        const changedFields = Object.keys(ORDER_STEP_FIELD_LABELS).filter((field) =>
            data[field] !== undefined && normalizeEmpty(data[field]) !== normalizeEmpty(existingSettings ? existingSettings[field] : undefined)
        );
        if (changedFields.length === 0) return null;

        const pick = (field) => (data[field] !== undefined ? data[field] : (existingSettings ? existingSettings[field] : null)) || null;
        const hasAnyValue = changedFields.some((field) => pick(field));
        if (!hasAnyValue) return null;

        const stepMaster = await orderStepService.loadActiveStepMaster(companyMasterData?.orderSteps);
        if (!stepMaster) {
            return common.returnResult(false, 400, "No order steps are assigned to your store yet, so the order step settings can't be saved. Please contact support.");
        }

        for (const field of changedFields) {
            const code = pick(field);
            if (code && !orderStepService.findStepByCode(stepMaster, code)) {
                return common.returnResult(false, 400, `${ORDER_STEP_FIELD_LABELS[field]}: "${code}" is not one of your store's order steps.`);
            }
        }

        const agentPairChanged = changedFields.includes('deliveryAgentFromStep') || changedFields.includes('deliveryAgentToStep');
        const fromCode = pick('deliveryAgentFromStep');
        const toCode = pick('deliveryAgentToStep');
        if (agentPairChanged && (fromCode || toCode)) {
            if (!orderStepService.isDeliveryAgentFeatureOn(websiteMasterData, companyMasterData)) {
                return common.returnResult(false, 403, 'Delivery agents are not enabled for your store.');
            }
            if (!fromCode || !toCode) {
                return common.returnResult(false, 400, 'Choose both the step a delivery agent moves an order from and the step it moves it to.');
            }
            const fromStep = orderStepService.findStepByCode(stepMaster, fromCode);
            const toStep = orderStepService.findStepByCode(stepMaster, toCode);
            const nextStep = orderStepService.getNextStep(stepMaster, fromStep.sequence);
            if (!nextStep) {
                return common.returnResult(false, 400, `"${fromStep.name}" is your last order step, so a delivery agent can't move an order on from it.`);
            }
            if (nextStep.code !== toStep.code) {
                return common.returnResult(false, 400, `A delivery agent can only move an order to the very next step - after "${fromStep.name}" that is "${nextStep.name}".`);
            }
        }
        return null;
    } catch (err) {
        throw err;
    }
};

// The vendor's assigned workflow, for the Company Settings step dropdowns.
const fetchAssignedOrderSteps = async (companyMasterData, websiteMasterData) => {
    try {
        const isDeliveryAgentAccessOn = orderStepService.isDeliveryAgentFeatureOn(websiteMasterData, companyMasterData);
        const stepMaster = await orderStepService.loadActiveStepMaster(companyMasterData?.orderSteps);
        if (!stepMaster) {
            return common.returnResult(true, 200, 'No order steps are assigned to this store yet', {
                steps: [], lastStepCode: null, isDeliveryAgentAccessOn
            });
        }

        const steps = orderStepService.getSortedSteps(stepMaster).map((step) => ({ code: step.code, name: step.name, sequence: step.sequence }));
        return common.returnResult(true, 200, 'Order steps fetched successfully', {
            steps,
            lastStepCode: orderStepService.getLastStep(stepMaster)?.code || null,
            isDeliveryAgentAccessOn
        });
    } catch (err) {
        throw err;
    }
};

