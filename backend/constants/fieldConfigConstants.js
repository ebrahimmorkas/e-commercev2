// Per-vendor field configuration (models/VendorFieldConfig.js): which built-in
// fields a vendor does not want to see, what they want some fields called, and
// which extra fields of their own they want added. One document per vendor per
// ENTITY (a module, e.g. 'product'), so a new vendor requirement is data, never
// a new CompanyMaster flag.
//
// FIELD_REGISTRY is the safety net. A config may only hide / rename / anchor a
// custom field to a field that is listed here, and the entry says how the field
// keeps doing its job once nobody sees it:
//   forcedSettingsWhenHidden - CompanySettings values that are forced while the
//       field is hidden (e.g. a hidden code is always auto-generated, whatever
//       the vendor's own setting says). Applied by
//       fieldConfigService.applyHiddenFieldSettings.
// A field is only listed once every place that shows it honours the config
// (form, lists, settings, storefront, Excel), so listing a new one = wiring it.

const FIELD_CONFIG_ENTITIES = {
    PRODUCT: 'product'
};

const FIELD_REGISTRY = {
    [FIELD_CONFIG_ENTITIES.PRODUCT]: {
        label: 'Product',
        fields: {
            productCode: {
                label: 'Product Code',
                hideable: true,
                renameable: true,
                forcedSettingsWhenHidden: { isProductCodeAutoGenerated: true }
            },
            variantCode: {
                label: 'Variant Code',
                hideable: true,
                renameable: true,
                forcedSettingsWhenHidden: { isVariantCodeAutoGenerated: true }
            },
            sizeCode: {
                label: 'Size Code',
                hideable: true,
                renameable: true,
                forcedSettingsWhenHidden: { isSizeCodeAutoGenerated: true }
            }
        }
    }
};

// Kinds of input a custom field can be.
const CUSTOM_FIELD_TYPES = {
    TEXT: 'text',
    NUMBER: 'number',
    SELECT: 'select'
};

// Where a custom field is drawn in a form:
//   replace - exactly where `field` used to be (the field should be hidden)
//   before / after - next to `field`
//   end - in the "Additional details" block at the end (default)
const CUSTOM_FIELD_PLACEMENTS = {
    REPLACE: 'replace',
    BEFORE: 'before',
    AFTER: 'after',
    END: 'end'
};

// A custom field key: starts with a letter, letters/digits only (it becomes an
// Excel column and a JSON key).
const CUSTOM_FIELD_KEY_PATTERN = /^[a-zA-Z][a-zA-Z0-9]{0,39}$/;

const MAX_CUSTOM_FIELDS_PER_ENTITY = 30;
const CUSTOM_FIELD_TEXT_MAX_LENGTH = 500;
const CUSTOM_FIELD_LABEL_MAX_LENGTH = 60;
const CUSTOM_FIELD_MAX_OPTIONS = 100;

module.exports = {
    FIELD_CONFIG_ENTITIES,
    FIELD_REGISTRY,
    CUSTOM_FIELD_TYPES,
    CUSTOM_FIELD_PLACEMENTS,
    CUSTOM_FIELD_KEY_PATTERN,
    MAX_CUSTOM_FIELDS_PER_ENTITY,
    CUSTOM_FIELD_TEXT_MAX_LENGTH,
    CUSTOM_FIELD_LABEL_MAX_LENGTH,
    CUSTOM_FIELD_MAX_OPTIONS
};
